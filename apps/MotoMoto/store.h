#pragma once

#include <cstdint>
#include <expected>
#include <filesystem>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

struct sqlite3;

namespace motomoto {

/// Mirror of the metadata schema enums (kept schema-agnostic: plain uint8 storage,
/// the caller converts to/from the generated types)
enum class RegisterStatus : std::uint8_t {
    Created = 0,
    Updated = 1,
    Unchanged = 2,
    Rejected = 3,
    UnknownService = 4,
};
enum class ServiceState : std::uint8_t {
    Active = 0,
    Inactive = 1,
};
enum class InstrumentType : std::uint8_t {
    Spot = 0,
    Future = 1,
    Option = 2,
    Spread = 3,
    Swap = 4,
};
enum class InstrumentState : std::uint8_t {
    Active = 0,
    Suspended = 1,
    Expired = 2,
    Delisted = 3,
};

/// A registered market data service, as published in ServiceDefinition
struct ServiceRow {
    std::string name; ///< unique service name (natural key)
    std::uint16_t serviceId;
    std::uint32_t version;
    std::int64_t reportedTs; ///< last time the service reported itself
    ServiceState state;
    std::string dataQueue;    ///< shm name of the multicast queue
    std::string requestQueue; ///< shm name of the MPSC queue
};

/// A registered instrument, as published in InstrumentDefinition
struct InstrumentRow {
    std::uint32_t instrumentId;
    std::string exchangeSymbol;
    std::string symbol; ///< internal name, never empty (generated by the store when not provided)
    std::uint16_t venueId;
    std::uint16_t serviceId; ///< market data service the instrument was created from
    InstrumentType instrumentType;
    InstrumentState state;
    std::optional<std::int64_t> tickSize; ///< Price9 mantissa, nullopt = no single tick size
    std::optional<std::int64_t> lotSize;  ///< Qty, nullopt = not applicable
    std::optional<std::int64_t> multiplier;
    std::optional<std::int64_t> expiry; ///< Timestamp, nullopt = perpetual
    std::optional<std::uint32_t> currency;
    std::uint16_t capabilities;
    std::uint32_t version;
    std::int64_t reportedTs; ///< last time a service reported the instrument
};

struct ServiceUpsertRequest {
    std::string_view name;
    std::string_view dataQueue;
    std::string_view requestQueue;
    ServiceState state;
    std::int64_t reportedTs;
};

struct ServiceUpsert {
    RegisterStatus status;
    std::uint16_t serviceId; ///< null (0xFFFF...) never happens here: Created/Updated/Unchanged carry an id
    std::uint32_t version;
};

struct InstrumentUpsertRequest {
    std::uint16_t serviceId; ///< must refer to a registered service
    std::uint16_t venueId;
    std::string_view exchangeSymbol;
    std::string_view symbol;       ///< empty: generated as "<serviceId>:<venueId>:<exchangeSymbol>";
                                   ///  ignored for existing entries: the stored symbol is immutable
    InstrumentType instrumentType; ///< immutable for a natural key: changing it is Rejected
    InstrumentState state;
    std::optional<std::int64_t> tickSize;
    std::optional<std::int64_t> lotSize;
    std::optional<std::int64_t> multiplier;
    std::optional<std::int64_t> expiry;
    std::optional<std::uint32_t> currency;
    std::uint16_t capabilities;
    std::int64_t reportedTs;
};

struct InstrumentUpsert {
    RegisterStatus status;
    std::optional<std::uint32_t> instrumentId; ///< nullopt when Rejected/UnknownService
    std::uint32_t version;
};

/// Filters are combined with AND; all empty = all services
struct ServiceQuery {
    std::optional<std::uint16_t> serviceId;
    std::optional<ServiceState> state;
    std::string_view name; ///< empty = any
};

/// Filters are combined with AND; all empty = all instruments.
/// A non-empty exchangeSymbol requires venueId (error otherwise)
struct InstrumentQuery {
    std::optional<std::uint32_t> instrumentId;
    std::optional<std::uint16_t> venueId;
    std::optional<std::uint16_t> serviceId;
    std::optional<InstrumentType> instrumentType;
    std::optional<InstrumentState> state;
    std::string_view exchangeSymbol; ///< empty = any
};

/// The instrument/service registry of MotoMoto, backed by SQLite.
/// The database is the source of truth: every operation runs in its own transaction
/// (WAL journal, synchronous=NORMAL: durability without a per-message fsync).
/// Ids are allocated from persistent counters and are never reused, even across restarts.
class Store {
public:
    /// Open (or create) the database and ensure the schema. Throws nothing; errors come as strings
    [[nodiscard]] static auto open(std::filesystem::path const& path) -> std::expected<Store, std::string>;

    Store(Store&&) noexcept;
    auto operator=(Store&&) noexcept -> Store&;
    ~Store();

    Store(Store const&) = delete;
    auto operator=(Store const&) = delete;

    /// Idempotent upsert by the natural key (the service name).
    /// Created: new entry, id allocated (monotonic, never reused). Updated: queue names or state
    /// changed, version incremented. Unchanged: same attributes, only reportedTs refreshed.
    [[nodiscard]] auto upsertService(ServiceUpsertRequest const& request) -> std::expected<ServiceUpsert, std::string>;

    /// Idempotent upsert by the natural key (serviceId, venueId, exchangeSymbol).
    /// serviceId must refer to a registered service, otherwise UnknownService.
    /// Created/Updated/Unchanged/Rejected semantics as for upsertService; instrumentType is immutable.
    [[nodiscard]] auto upsertInstrument(InstrumentUpsertRequest const& request)
        -> std::expected<InstrumentUpsert, std::string>;

    /// Services matching the AND-combined filters, in serviceId order
    [[nodiscard]] auto queryServices(ServiceQuery const& query) -> std::expected<std::vector<ServiceRow>, std::string>;

    /// Instruments matching the AND-combined filters, in instrumentId order
    [[nodiscard]] auto queryInstruments(InstrumentQuery const& query)
        -> std::expected<std::vector<InstrumentRow>, std::string>;

private:
    explicit Store(sqlite3* db) noexcept;

    sqlite3* db_ = nullptr; // freed via sqlite3_close() in the destructor (complete type there)
};

} // namespace motomoto
